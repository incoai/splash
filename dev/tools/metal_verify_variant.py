#!/usr/bin/env python3
"""Generate an isolated sixteen-row translation unit from production source."""
from __future__ import annotations

import argparse
from pathlib import Path


def wrapper(source: str) -> str:
    path = Path(source)
    if path.is_absolute() or ".." in path.parts or path.suffix != ".metal":
        raise ValueError("variant source must be a repository-relative Metal file")
    include = path.relative_to("runtime").as_posix()
    if not include.startswith("metal/kernels/"):
        raise ValueError("variant source must be a production kernel")
    return f'''// Generated by dev/tools/metal_verify_variant.py; edit the original source.
#include <MetalPerformancePrimitives/MetalPerformancePrimitives.h>
#include <metal_stdlib>
#define SPLASH_DRAFT_QUERY_ROWS 16u
#define SPLASH_DRAFT_PROPOSAL_TOKENS 15u
#define SPLASH_TARGET_VERIFY_ROWS 16u
#define SPLASH_KERNEL_SUFFIX "_v16"
// The standard modules above belong to global scope. ABI/common headers
// import them redundantly; ignore only that redundant-import diagnostic.
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wmodules-import-nested-redundant"
namespace splash_verify16 {{
#include "{include}"
}}
#pragma clang diagnostic pop
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source")
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    data = wrapper(args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != data:
        args.output.write_text(data)


if __name__ == "__main__":
    main()
