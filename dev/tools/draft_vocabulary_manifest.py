"""Content identities for an offline draft-vocabulary generation."""

import hashlib
import importlib.metadata
import json
import shlex
from pathlib import Path


def digest(path):
    value = hashlib.sha256()
    with open(path, "rb") as source:
        for block in iter(lambda: source.read(1 << 20), b""):
            value.update(block)
    return value.hexdigest()


def capture_inputs(tokenizer, corpus, code_files):
    """Capture before generation, including an old output used as code input."""
    return {
        "tokenizer": {"path": str(tokenizer), "sha256": digest(tokenizer)},
        "corpus": [
            {"file": p.name, "sha256": digest(p)}
            for p in sorted(Path(corpus).iterdir())
            if p.is_file()
        ],
        "code": [{"file": str(p), "sha256": digest(p)} for p in sorted(code_files)],
    }


def write_manifest(
    path, tokenizer, corpus, code_files, bitmap, invocation, *, inputs=None
):
    """Pin the bytes supplied to a generation, without requiring mutable URLs."""
    if inputs is None:
        inputs = capture_inputs(tokenizer, corpus, code_files)
    record = {
        "schema": 1,
        "exact_invocation": shlex.join(invocation),
        "inputs": inputs,
        "input_identity_sha256": hashlib.sha256(
            json.dumps(inputs, sort_keys=True).encode()
        ).hexdigest(),
        "generated_cpp_sha256": digest(bitmap),
        "packages": {
            name: importlib.metadata.version(name)
            for name in ("numpy", "pyarrow", "tokenizers")
        },
    }
    Path(path).write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")


def manifest_path(bitmap):
    """The record beside a generated C++ bitmap, including the checked-in one."""
    return Path(bitmap).with_suffix(".manifest.json")


def validate_manifest(bitmap, path=None):
    """Validate both legacy and newly generated records with the same schema."""
    record = json.loads(Path(path or manifest_path(bitmap)).read_text())
    if record["schema"] != 1 or record["generated_cpp_sha256"] != digest(bitmap):
        raise ValueError("draft vocabulary manifest does not match generated bytes")
    invocation = record["exact_invocation"]
    if invocation is None:
        if record.get("status") != "legacy generation; historical inputs unrecorded":
            raise ValueError("only a legacy record may lack its exact invocation")
    else:
        if not isinstance(invocation, str) or not invocation:
            raise ValueError("generation requires an exact invocation")
        identity = hashlib.sha256(
            json.dumps(record["inputs"], sort_keys=True).encode()
        ).hexdigest()
        if record["input_identity_sha256"] != identity:
            raise ValueError("draft vocabulary input identity differs")
    return record
